export const STRINGS = STR;

function pickLang() {
  const q = new URLSearchParams(location.search).get('lang');
  if (q && STR[q]) {
    try {
      localStorage.setItem('princessDay.lang', q);
    } catch {
      /* storage blocked: the choice just lasts for this visit */
    }
    return q;
  }
  try {
    const saved = localStorage.getItem('princessDay.lang');
    if (saved && STR[saved]) return saved;
  } catch {
    /* ignore */
  }
  return 'et';
}

export const lang = pickLang();

// t('ui.day', { n: 3 }) -> 'Päev 3'. Arrays (counting words etc.) come back as arrays.
export function t(key, vars) {
  const v = STR[lang][key] ?? STR.en[key] ?? key;
  if (typeof v !== 'string' || !vars) return v;
  return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
}

// fill the fixed text in index.html
export function applyStatic() {
  document.documentElement.lang = lang;
  document.title = t('ui.title');
  document.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
}
